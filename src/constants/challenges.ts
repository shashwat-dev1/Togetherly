/**
 * Returns deterministic daily challenge for any given date string (YYYY-MM-DD).
 * Both partners will ALWAYS see the exact identical daily challenge worldwide.
 */
export function getDailyChallengeForDate(dateStr: string): DailyChallenge {
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash << 5) - hash + dateStr.charCodeAt(i);
    hash |= 0;
  }
  const idx = Math.abs(hash) % CHALLENGE_BANK.length;
  const template = CHALLENGE_BANK[idx];

  return {
    id: `${dateStr}_${template.id}`,
    date: dateStr,
    title: template.title,
    description: template.description,
    category: template.category,
    targetGameId: template.targetGameId,
    targetCount: template.targetCount,
    rewardXP: template.rewardXP,
    hint: template.hint,
  };
}

/**
 * Helper to get formatted local date (YYYY-MM-DD).
 */
export function getCurrentDateString(date: Date = new Date()): string {
  const y = date.getUTCFullYear();
  const m = String(date.getUTCMonth() + 1).padStart(2, '0');
  const d = String(date.getUTCDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

